def load_preset_config():
    presets = json.loads(Path(__file__).with_name("byteplus_presets.json").read_text(encoding="utf-8"))
    by_id = {item["id"]: item for item in presets}
    for category, subcategories in PRESET_CATEGORIES.items():
        for subcategory, ids in subcategories.items():
            for preset_id in ids.split():
                by_id[preset_id].update(category=category, subcategory=subcategory,
                                        scene_prompt=PRESET_SCENE_PROMPTS.get(preset_id, ""))
    for preset_id, category, subcategory, name, base_id, scene in ADDITIONAL_PRESETS:
        presets.append(dict(id=preset_id, name=name, category=category, subcategory=subcategory,
                            style=deepcopy(by_id[base_id]["style"]), scene_prompt=scene))
    return presets


@dataclass(frozen=True, slots=True)
class ByteplusConfig:
    api_key: str
    api_base_url: str = "https://voice.ap-southeast-1.bytepluses.com"
    resource_id: str = "seed-tts-2.0"
    user_id: str = "concierge-audio"
    connect_timeout_seconds: float = 10.0
    read_timeout_seconds: float = 120.0
    max_segments: int = 50

    @classmethod
    def from_env(cls) -> "ByteplusConfig":
        return cls(
            api_key=os.getenv("BYTEPLUS_API_KEY", "").strip(),
            api_base_url=os.getenv(
                "BYTEPLUS_API_BASE_URL",
                "https://voice.ap-southeast-1.bytepluses.com",
            ).rstrip("/"),
            resource_id=os.getenv(
                "BYTEPLUS_TTS_RESOURCE_ID",
                "seed-tts-2.0",
            ).strip(),
            user_id=os.getenv("BYTEPLUS_TTS_USER_ID", "concierge-audio").strip(),
            connect_timeout_seconds=float(
                os.getenv("BYTEPLUS_CONNECT_TIMEOUT_SECONDS", "10")
            ),
            read_timeout_seconds=float(
                os.getenv("BYTEPLUS_READ_TIMEOUT_SECONDS", "120")
            ),
            max_segments=int(os.getenv("BYTEPLUS_MAX_SEGMENTS", "50")),
        )
